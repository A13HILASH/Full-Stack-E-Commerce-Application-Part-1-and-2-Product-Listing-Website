"""Dynamic CSS generation: validated theme settings -> CSS file."""
import json
import re

from fastapi import APIRouter
from fastapi.responses import Response
from pydantic import BaseModel, Field, field_validator

from .db import get_conn

router = APIRouter(tags=["theme"])
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")

# System font stacks only, so the site stays fully offline-capable.
FONTS = {
    "system": ("System UI", 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif'),
    "humanist": ("Humanist (Avenir / Segoe)", '"Avenir Next", "Segoe UI", Candara, "Gill Sans", sans-serif'),
    "rounded": ("Rounded (Trebuchet)", '"Trebuchet MS", "Lucida Grande", Verdana, sans-serif'),
    "serif": ("Serif (Georgia)", 'Georgia, "Times New Roman", serif'),
    "classic": ("Classic (Palatino)", '"Palatino Linotype", Palatino, "Book Antiqua", serif'),
    "mono": ("Monospace", 'ui-monospace, "SF Mono", Consolas, "Courier New", monospace'),
}
COLOR_KEYS = ["bg", "card", "ink", "muted", "line", "accent", "accent_ink", "header_bg", "header_ink"]


class Theme(BaseModel):
    bg: str = "#f3f5f7"
    card: str = "#ffffff"
    ink: str = "#1b2430"
    muted: str = "#5d6877"
    line: str = "#d9dee5"
    accent: str = "#0e6b62"
    accent_ink: str = "#ffffff"
    header_bg: str = "#1b2430"
    header_ink: str = "#ffffff"
    font_body: str = "humanist"
    font_heading: str = "humanist"
    base_size: int = Field(16, ge=12, le=22)
    radius: int = Field(10, ge=0, le=28)

    @field_validator(*COLOR_KEYS)
    @classmethod
    def _hex(cls, v):
        if not HEX.match(v):
            raise ValueError("must be a 6-digit hex colour like #1b2430")
        return v.lower()

    @field_validator("font_body", "font_heading")
    @classmethod
    def _font(cls, v):
        if v not in FONTS:
            raise ValueError(f"must be one of: {', '.join(FONTS)}")
        return v


PRESETS = {
    "default": {},
    "midnight": dict(bg="#10151c", card="#19212b", ink="#e8edf3", muted="#9aa7b5", line="#2a3441", accent="#4fd1c5",
                     accent_ink="#08201e", header_bg="#0a0e13", header_ink="#e8edf3", font_body="system",
                     font_heading="system", radius=12),
    "forest": dict(bg="#f1f5ee", ink="#1f2e22", muted="#5b6b5e", line="#d3ddcf", accent="#2f6b3a",
                   header_bg="#1f3a27", header_ink="#f1f5ee", font_heading="serif", radius=4),
    "plum": dict(bg="#f7f3f8", ink="#2a1830", muted="#6e5a76", line="#e3d8e8", accent="#8a2e8f",
                 header_bg="#3a1a44", font_body="rounded", font_heading="rounded", radius=18),
    "mono": dict(bg="#f5f5f5", ink="#111111", muted="#666666", line="#dddddd", accent="#111111",
                 header_bg="#ffffff", header_ink="#111111", font_body="mono", font_heading="mono", radius=0),
}


def generate_css(t: Theme) -> str:
    v = t.model_dump()
    return f"""/* Hearth & Desk theme - generated by the admin dashboard.
   To use offline: save as frontend/theme.css and change the <link> in index.html to /theme.css */
:root {{
  --bg: {v['bg']};
  --card: {v['card']};
  --ink: {v['ink']};
  --muted: {v['muted']};
  --line: {v['line']};
  --accent: {v['accent']};
  --accent-ink: {v['accent_ink']};
  --header-bg: {v['header_bg']};
  --header-ink: {v['header_ink']};
  --radius: {v['radius']}px;
}}
html {{ font-size: {v['base_size']}px; }}
body {{ font-family: {FONTS[v['font_body']][1]}; }}
h1, h2, h3, .brand, .price {{ font-family: {FONTS[v['font_heading']][1]}; }}
.card, .filters, .detail img, .search input, button.btn,
.filters input[type=number], .filters select, .bar select {{ border-radius: var(--radius); }}
"""


def load_theme(conn) -> Theme:
    row = conn.execute("SELECT data FROM theme_settings WHERE id = 1").fetchone()
    return Theme(**json.loads(row["data"])) if row else Theme()


@router.get("/api/theme.css", summary="Live stylesheet for the storefront")
def theme_css():
    conn = get_conn()
    try:
        return Response(generate_css(load_theme(conn)), media_type="text/css", headers={"Cache-Control": "no-cache"})
    finally:
        conn.close()


@router.get("/api/admin/theme")
def get_theme():
    conn = get_conn()
    try:
        return {
            "theme": load_theme(conn).model_dump(),
            "fonts": {k: label for k, (label, _) in FONTS.items()},
            "presets": {k: Theme(**p).model_dump() for k, p in PRESETS.items()},
        }
    finally:
        conn.close()


@router.put("/api/admin/theme")
def save_theme(theme: Theme):
    conn = get_conn()
    try:
        conn.execute(
            """INSERT INTO theme_settings (id, data, updated_at) VALUES (1, ?, datetime('now'))
               ON CONFLICT(id) DO UPDATE SET data = excluded.data, updated_at = excluded.updated_at""",
            (theme.model_dump_json(),),
        )
        conn.commit()
        return theme.model_dump()
    finally:
        conn.close()


@router.post("/api/admin/theme/css", summary="Generate CSS from (unsaved) settings, for preview/download")
def preview_css(theme: Theme):
    return Response(generate_css(theme), media_type="text/css")


@router.delete("/api/admin/theme", status_code=204)
def reset_theme():
    conn = get_conn()
    try:
        conn.execute("DELETE FROM theme_settings")
        conn.commit()
    finally:
        conn.close()
